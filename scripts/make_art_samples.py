"""Regenerate the CB2A sample exports in ./samples/art by running the real Art Direction workflow against a throwaway database.

    .venv\\Scripts\\python.exe scripts\\make_art_samples.py

Local, deterministic code only (no network, no AI, no Dreambox). Safe to re-run; it overwrites only files in ./samples/art.
The screenplay is "The Closing Hour", unchanged for both treatments. Approvals and the reviewer name are scripted stand-ins
for a person's decisions. The sample picture is a tiny generated PNG, not an artwork.
"""
import json
import struct
import sys
import tempfile
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.art import ArtService  # noqa: E402
from app.core import get_fixture  # noqa: E402
from app.experiments import ExperimentService  # noqa: E402
from app.lab import LabService  # noqa: E402

OUT = ROOT / "samples" / "art"
REVIEWER = "Sample Art Director"


def png(rgb):
    """A 8x8 solid-colour PNG, built by hand so the sample needs no imaging library."""
    raw = b"".join(b"\x00" + bytes(rgb) * 8 for _ in range(8))

    def chunk(tag, body):
        return struct.pack(">I", len(body)) + tag + body + struct.pack(">I", zlib.crc32(tag + body) & 0xFFFFFFFF)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 8, 8, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b"")


def write(name, data):
    path = OUT / name
    path.parent.mkdir(parents=True, exist_ok=True)
    text = data if isinstance(data, str) else json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    path.write_text(text, encoding="utf-8", newline="\n")


def main():
    with tempfile.TemporaryDirectory() as tmp:
        data_dir = Path(tmp)
        svc = ExperimentService(data_dir / "samples.db")
        lab = LabService(svc)
        art = ArtService(svc, lab, data_dir)
        doc = get_fixture("screenwriting", "screenplay")
        sp_exp = svc.create_experiment("screenwriting", "The Closing Hour", doc)
        sp_run = svc.run_experiment(sp_exp["id"])
        sp = sp_run["envelope"]["artifact"]
        plan = lab.draft_plan(sp_exp["id"], "SC-001", {"preset": "intimate"}, "Plan A (intimate)")
        plan_exp = plan["experiment"]["id"]

        # one registered picture, so the asset manifest has something real to point at
        stored = art.upload(png((139, 94, 60)), "oak-grain.png")
        reg_in = {"schema": "filmcraft.asset_register.v1", "project_id": sp["project"]["id"], "assets": [
            {"id": "A-001", "name": "Oak grain", "kind": "texture", "sha256": stored["sha256"], "filename": "oak-grain.png", "size_bytes": stored["size_bytes"],
             "mime": stored["mime"], "source": {"type": "own", "creator": "Sample"}, "rights": {"status": "cleared", "owner": "Sample", "licence": "own work"},
             "usage": {"allowed": ["film"]}, "tags": ["wood", "warm"]}]}
        reg_exp = svc.create_experiment("art_direction", "Sample asset register", reg_in)
        svc.run_experiment(reg_exp["id"])

        runs = {}
        for key, preset, name in (("A", "warm_nostalgia", "Warm nostalgia"), ("B", "emotional_distance", "Emotional distance")):
            made = art.draft(sp_exp["id"], "SC-001", preset, name, plan_experiment_id=plan_exp)
            run_id = made["latest_run"]["id"] if "latest_run" in made else made["run"]["id"]
            if key == "A":                                    # treatment A uses the registered oak picture as its wood reference
                doc_a = svc.get_run(run_id)["envelope"]["artifact"]
                doc_a["asset_ids"] = ["A-001"]
                saved = art.save(made["id"] if "id" in made else made["experiment"]["id"], doc_a, name, "References the oak grain picture")
                run_id = saved["run"]["id"] if "run" in saved else saved["latest_run"]["id"]
            svc.submit_for_review(run_id, REVIEWER)
            svc.approve(run_id, REVIEWER, "Sample approval")
            runs[key] = run_id
            tag = f"treatment-{key}-{preset.replace('_', '-')}"
            for kind, label in (("art-direction-json", "art-direction.json"), ("storyboard-metadata", "storyboard-metadata.json"),
                                ("art-direction-manifest", "art-direction-manifest.json"), ("asset-reference-manifest", "asset-reference-manifest.json")):
                out = art.export(run_id, kind)
                write(f"{tag}.{label}", out["data"])
            write(f"{tag}.props.csv", art.export(run_id, "prop-list-csv")["text"])
        write("treatments-A-vs-B.comparison.json", art.compare(runs["A"], runs["B"]))
        write("README.md", README)
    print(f"Wrote {sum(1 for p in OUT.rglob('*') if p.is_file())} files to {OUT}")


README = """# CB2A sample exports: "The Closing Hour"

Generated by `scripts/make_art_samples.py` from the real Craftbox Art Direction workflow (no AI, no images made, no network).
The screenplay is the same for both treatments; only the design differs.

| File | What it is |
|---|---|
| `treatment-A-warm-nostalgia.*` | Treatment A: aged wood, warm light, personal objects. Art direction (JSON), storyboard/previz notes, prop list (CSV), art direction manifest, asset reference manifest |
| `treatment-B-emotional-distance.*` | Treatment B: minimalist, cool, open and sparse. Same set of files |
| `treatments-A-vs-B.comparison.json` | Measures behind each reading, so the difference is explained, not just asserted |

The two manifests (`filmcraft.art_direction_manifest.v1`, `filmcraft.asset_reference_manifest.v1`) carry sections prepared for Lighting,
Costume, Cinematography and a future Dreambox Scene Maker adapter. They are inert files: `auto_import` is false and nothing here
touches Dreambox. Approvals, the reviewer name and timestamps are scripted; the one registered picture is a generated 8x8 swatch.
"""

if __name__ == "__main__":
    main()
