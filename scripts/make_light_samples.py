"""Regenerate the CB2B sample exports in ./samples/light by running the real Lighting workflow against a throwaway database.

    .venv\\Scripts\\python.exe scripts\\make_light_samples.py

Local, deterministic code only (no network, no AI, no Dreambox). Safe to re-run; it overwrites only files in ./samples/light.
The screenplay is "The Closing Hour", unchanged for both treatments. Approvals and the reviewer names are scripted stand-ins
for a person's decisions.
"""
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.art import ArtService  # noqa: E402
from app.core import get_fixture  # noqa: E402
from app.experiments import ExperimentService  # noqa: E402
from app.lab import LabService  # noqa: E402
from app.light import LightService  # noqa: E402

OUT = ROOT / "samples" / "light"
REVIEWER = "Sample Gaffer"

TREATMENTS = (("A", "warm_nostalgia", "Warm nostalgia", "warm_naturalistic", "Warm, naturalistic, intimate"),
              ("B", "emotional_distance", "Emotional distance", "cool_dramatic", "Cool, restrained, dramatic"))


def write(name, data):
    path = OUT / name
    path.parent.mkdir(parents=True, exist_ok=True)
    text = data if isinstance(data, str) else json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    path.write_text(text, encoding="utf-8", newline="\n")


def main():
    with tempfile.TemporaryDirectory() as tmp:
        data_dir = Path(tmp)
        svc = ExperimentService(data_dir / "samples.db")
        lab = LabService(svc)
        art = ArtService(svc, lab, data_dir)
        light = LightService(svc, lab, art, data_dir)
        sp_exp = svc.create_experiment("screenwriting", "The Closing Hour", get_fixture("screenwriting", "screenplay"))
        svc.run_experiment(sp_exp["id"])
        plan = lab.draft_plan(sp_exp["id"], "SC-001", {"preset": "intimate"}, "Plan A (intimate)")
        plan_exp = plan["experiment"]["id"]

        runs, first_plan = {}, None
        for key, art_preset, art_name, light_preset, name in TREATMENTS:
            made = art.draft(sp_exp["id"], "SC-001", art_preset, art_name, plan_experiment_id=plan_exp)
            art_exp = made["experiment"]["id"] if "experiment" in made else made["id"]
            art_run = made["run"]["id"] if "run" in made else made["latest_run"]["id"]
            svc.submit_for_review(art_run, "Sample Art Director")
            svc.approve(art_run, "Sample Art Director", "Sample approval of the art design")
            lp = light.draft(sp_exp["id"], art_exp, light_preset, name, plan_experiment_id=plan_exp)
            run_id = lp["run"]["id"]
            svc.submit_for_review(run_id, REVIEWER)
            svc.approve(run_id, REVIEWER, "Sample approval")
            runs[key] = run_id
            first_plan = first_plan or lp["experiment"]["id"]
            tag = f"treatment-{key}-{light_preset.replace('_', '-')}"
            for kind, label in (("lighting-plan-json", "lighting-plan.json"), ("lighting-instructions", "lighting-instructions.json"), ("lighting-manifest", "lighting-manifest.json")):
                write(f"{tag}.{label}", light.export(run_id, kind)["data"])
            write(f"{tag}.light-schedule.csv", light.export(run_id, "light-schedule-csv")["text"])
        write("treatments-A-vs-B.comparison.json", light.compare(runs["A"], runs["B"]))
        saved = light.save_setup(first_plan, "WARM-ROOM", "Warm room", "The warm, naturalistic rig, kept so another scene can start from it.")
        write("setup-WARM-ROOM.lighting-setup.json", light.export(saved["run"]["id"], "lighting-setup-json")["data"])
        write("README.md", README)
    print(f"Wrote {sum(1 for p in OUT.rglob('*') if p.is_file())} files to {OUT}")


README = """# CB2B sample exports: "The Closing Hour"

Generated by `scripts/make_light_samples.py` from the real Craftbox Lighting workflow (no AI, no rendering, no network).
The screenplay and the director's plan are the same for both treatments; only the art design and the lighting differ.

| File | What it is |
|---|---|
| `treatment-A-warm-naturalistic.*` | Lighting for art treatment A (warm nostalgia): the plan (JSON), per-shot lighting instructions (JSON), the light schedule (CSV) and the approved lighting manifest |
| `treatment-B-cool-dramatic.*` | Lighting for art treatment B (emotional distance). Same set of files |
| `treatments-A-vs-B.comparison.json` | The measured settings behind each stated effect, so the difference is explained and not only asserted |
| `setup-WARM-ROOM.lighting-setup.json` | A reusable setup saved from plan A, which can start a plan in another scene |

The lighting files hold lighting data only. They point at the art treatment by id and hash and do not copy its design.
Positions and levels are planning estimates on the director's stage plan, not a physical lighting simulation.
The manifests are inert: `auto_import` is false and nothing here touches Dreambox. Approvals, reviewer names and timestamps are scripted.
"""

if __name__ == "__main__":
    main()
